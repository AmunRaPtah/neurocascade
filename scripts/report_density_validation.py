#!/usr/bin/env python
"""P4.2: write the committed record of how well expression predicts density.

    python scripts/report_density_validation.py

Needs the gitignored `data/expression` and `data/connectome` caches
(`scripts/fetch_expression.py`, `scripts/fetch_connectome.py`). Writes
`results/expression_density_validation.txt`.

Like `report_expression_coverage.py` this file is documentation, not an
input to anything: `tests/test_expression_density.py` re-derives the
headline numbers, offline from the committed fixtures for the Yoo et al.
2010 D1 comparison and the two measured mismatch displacements, and from
the real cache for the Lothmann et al. 2021 breadth sweep.

The point of committing it is that P4.2's assumption and the measured size
of its error are readable in a clean checkout without the caches and
without running anything. Every number printed here is computed from the
published tables in `expression/autoradiography.py` and the Allen unionizes;
nothing is copied from a docstring.
"""

import argparse
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))

from neurocascade import connectome, expression  # noqa: E402
from neurocascade.expression import autoradiography, mismatch, validation  # noqa: E402

RESULTS = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    "..",
    "results",
    "expression_density_validation.txt",
)

RULE = "=" * 72
THIN = "-" * 72

#: The policy the headline numbers use. Coronal experiments cover the whole
#: brain; `mean` over the coronal experiments of a gene is the least
#: opinionated reduction. `policy_sensitivity()` below reports what every
#: other policy would have given, which is the honest way to have a default.
PLANE = "coronal-else-sagittal"
COMBINE = "mean"


def _regions_for(binding, ontology, extra=()):
    acronyms = sorted(binding.mapped(ontology=ontology)) + list(extra)
    return [ontology.id_for_acronym(a) for a in acronyms]


def report(out, cache_dir=None):
    ontology = connectome.load_ontology()
    atlas = expression.load_expression_atlas(ontology=ontology, cache_dir=cache_dir)

    out("Expression energy as a receptor density: what it is worth (P4.2)")
    out(RULE)
    out("")
    out("THE ASSUMPTION UNDER TEST")
    out("")
    for line in _wrap(expression.ASSUMPTION):
        out("  " + line)
    out("")
    out("Generated by scripts/report_density_validation.py.")
    out("Expression policy for every number below: plane=%r, combine=%r."
        % (PLANE, COMBINE))
    out("")

    # --- 1. the primary comparison ----------------------------------------
    out(THIN)
    out("1. Drd1 against measured mouse D1 receptor density")
    out(THIN)
    out("")
    dataset = autoradiography.YOO2010
    out("  %s" % dataset.citation)
    out("  PMID %s, doi %s" % (dataset.pmid, dataset.doi))
    out("  %s, %s, %s, %s, n = %s"
        % (dataset.species, dataset.strain, dataset.sex, dataset.age,
           dataset.n_animals))
    out("  %s" % dataset.method)
    out("")

    binding = autoradiography.yoo2010_d1()
    ids = _regions_for(binding, ontology)
    energy = atlas.energy_matrix(ids, symbols=["Drd1"], plane=PLANE, combine=COMBINE)
    comparison = validation.compare(energy, "Drd1", binding)
    for line in comparison.describe().splitlines():
        out("  " + line)
    out("")
    out("  region-by-region:")
    out("    %-6s %14s %14s %10s" % ("region", "ISH energy", "fmol/mg", "meas/pred"))
    ratios = comparison.ratios()
    for i, acronym in enumerate(comparison.acronyms):
        out("    %-6s %14.3f %14.1f %10.2f"
            % (acronym, comparison.energy[i], comparison.measured[i], ratios[i]))
    out("")
    out("  published regions NOT in the comparison, and why:")
    for name, reason in validation.dropped_regions(energy, "Drd1", binding):
        out("    %s" % name)
        for line in _wrap(reason, 64):
            out("      " + line)
    out("")

    scale = validation.fit_absolute_scale(comparison)
    out("  fitted absolute scale: k_Drd1 = %.4g %s per expression-energy unit"
        % (scale.factor, scale.units))
    out("    fitted on %d regions, R2 %+.3f. The R2 travels with the constant"
        % (scale.n_regions, scale.r_squared))
    out("    because a k fitted this loosely is a real number and a bad one.")
    out("")

    out("  the same comparison with 'substantia nigra' joined to SNr:")
    sn_energy = atlas.energy_matrix(
        _regions_for(binding, ontology, extra=("SNr",)),
        symbols=["Drd1"], plane=PLANE, combine=COMBINE,
    )
    with_sn = validation.compare(
        sn_energy, "Drd1", binding, extra_regions={"SNr": "Substantia nigra"}
    )
    rho, p = with_sn.spearman
    out("    n = %d, Spearman rho %+.3f (p = %.4g), proportional R2 %+.3f"
        % (with_sn.n, rho, p, with_sn.proportional_r2))
    out("    SNr is the single largest disagreement in the whole comparison")
    out("    and it is not a measurement problem; see section 3.")
    out("")

    out("  the accumbens, which CCF does not subdivide and Yoo et al. do:")
    for name, values in sorted(autoradiography.ACCUMBENS_SUBDIVISIONS["D1"].items()):
        out("    %-26s %6.1f (B6), %6.1f (129), %6.1f (B6x129)"
            % ((name,) + values))
    out("")

    out("  how much the P4.1 plane/combine choice moves the answer:")
    sensitivity = validation.policy_sensitivity(
        atlas, "Drd1", binding, ids, ontology=ontology
    )
    for plane, combine, n, rho in sensitivity:
        out("    plane=%-22s combine=%-7s n=%2d  rho %+.3f"
            % (plane, combine, n, rho))
    rhos = [r for _, _, _, r in sensitivity]
    out("    range %.3f to %.3f over %d policies."
        % (min(rhos), max(rhos), len(rhos)))
    out("")

    # --- 2. D2, as an ordering check --------------------------------------
    out(THIN)
    out("2. Drd2 against measured mouse D2 receptor density")
    out(THIN)
    out("")
    d2 = autoradiography.yoo2010_d2()
    out("  %s" % d2.note)
    out("")
    d2_ids = _regions_for(d2, ontology)
    d2_energy = atlas.energy_matrix(
        d2_ids, symbols=["Drd2"], plane=PLANE, combine=COMBINE
    )
    d2_row = d2_energy.for_gene("Drd2")
    out("    %-6s %14s %14s" % ("region", "ISH energy", "fmol/mg"))
    densities = d2.mapped(ontology=ontology)
    for acronym in sorted(densities):
        index = [int(i) for i in d2_energy.structure_ids].index(
            ontology.id_for_acronym(acronym)
        )
        out("    %-6s %14.3f %14.1f" % (acronym, d2_row[index], densities[acronym]))
    for name, values in sorted(autoradiography.ACCUMBENS_SUBDIVISIONS["D2"].items()):
        out("    %-26s %6.1f (B6)  [no CCF counterpart]" % (name, values[0]))
    out("")

    # --- 3. the mismatch --------------------------------------------------
    out(THIN)
    out("3. Where the transcript map puts the receptor in the wrong region")
    out(THIN)
    out("")
    out("  Measured cases (both sides quantified in mouse):")
    out("")
    for symbol in ("Slc6a3", "Drd1"):
        record = mismatch.mismatch_for(symbol)
        pair_ids = [
            ontology.id_for_acronym(a) for a in (record.measured[1], record.measured[2])
        ]
        pair = atlas.energy_matrix(
            pair_ids, symbols=[symbol], plane=PLANE, combine=COMBINE
        )
        displacement = mismatch.measured_displacement(pair, symbol)
        for line in _wrap(displacement.describe(), 68):
            out("    " + line)
        out("      transcript  %-4s %9.3f   %-4s %9.3f"
            % (displacement.soma, displacement.soma_energy,
               displacement.terminal, displacement.terminal_energy))
        out("      %-11s %-4s %9.1f   %-4s %9.1f  %s"
            % (displacement.ligand, displacement.soma, displacement.soma_density,
               displacement.terminal, displacement.terminal_density,
               autoradiography.YOO2010.key))
        out("")
    out("  Documented but not quantified (no mouse table with both sides):")
    out("")
    for record in mismatch.MISMATCHES:
        if record.measured is not None:
            continue
        out("    %s [%s]  %s -> %s"
            % (record.symbol, record.severity,
               "/".join(record.soma_regions), "/".join(record.terminal_regions)))
    out("")
    out("  Genes deliberately NOT in the registry: the ionotropic receptors")
    out("  (Grin*, Gria*, Gabra*, Gabrb*), which are predominantly")
    out("  postsynaptic on the dendrites of the cell that transcribes them.")
    out("  Their absence is an assertion about them, not an oversight.")
    out("")

    # --- 4. breadth -------------------------------------------------------
    out(THIN)
    out("4. Seven receptor systems at once: the olfactory-system sweep")
    out(THIN)
    out("")
    dataset = autoradiography.LOTHMANN2021
    out("  %s" % dataset.citation)
    out("  PMID %s, doi %s" % (dataset.pmid, dataset.doi))
    out("  %s, %s, %s, %s, n = %s"
        % (dataset.species, dataset.strain, dataset.sex, dataset.age,
           dataset.n_animals))
    out("")
    out("  Each row is ONE gene against the ligand that labels its product,")
    out("  over the same fourteen regions. Rank correlations only: expression")
    out("  energy is not comparable between genes, so the columns are not")
    out("  comparable to each other in absolute terms.")
    out("")
    out("  %-11s %-9s %-9s %4s %8s %8s %10s"
        % ("receptor", "ligand", "gene", "n", "rho", "p", "loglog b"))
    for receptor in autoradiography.comparable_lothmann_receptors():
        ligand_binding = autoradiography.lothmann2021(receptor)
        region_ids = _regions_for(ligand_binding, ontology)
        genes = [g for g in ligand_binding.genes if g in atlas]
        if not genes:
            continue
        grid = atlas.energy_matrix(
            region_ids, symbols=genes, plane=PLANE, combine=COMBINE
        )
        for symbol in genes:
            item = validation.compare(grid, symbol, ligand_binding)
            rho, p = item.spearman
            out("  %-11s %-9s %-9s %4d %+8.3f %8.4g %10.2f"
                % (receptor, ligand_binding.ligand[:9], symbol, item.n,
                   rho, p, item.loglog[0]))
        missing = [g for g in ligand_binding.genes if g not in atlas]
        if missing:
            out("  %-11s %-9s %s"
                % ("", "", "not ingested, so unattributed: " + ", ".join(missing)))
    out("")
    out("  The spread across receptors is the result. The proportionality")
    out("  assumption is not uniformly good or uniformly bad: it is")
    out("  receptor-specific, and a whole-brain map built on it inherits")
    out("  that unevenness receptor by receptor.")
    out("")

    out(THIN)
    out("5. Receptors with no usable density data")
    out(THIN)
    out("")
    for entry in autoradiography.SEARCHED_AND_EMPTY:
        out("  %s" % entry["receptor"])
        for label in ("why_wanted", "searched", "conclusion"):
            out("    %s:" % label.replace("_", " "))
            for line in _wrap(entry[label], 64):
                out("      " + line)
        out("")

    # --- 6. uncertainty ---------------------------------------------------
    out(THIN)
    out("6. How much of the disagreement is measurement noise")
    out(THIN)
    out("")
    out("  Yoo et al. measured three mouse genetic backgrounds on the same")
    out("  films. The spread between them is a floor on how precisely any")
    out("  single published density number can be read:")
    out("")
    for receptor, (median, worst_region, worst) in sorted(
        autoradiography.background_spread().items()
    ):
        out("    %-4s median max/min across backgrounds %.2f, worst %s %.2f"
            % (receptor, median, worst_region, worst))
    out("")
    out("  Against that, the proportional model's per-region errors in")
    out("  section 1 run to a factor of 29. The disagreement is not noise.")
    out("")


def _wrap(text, width=68):
    words = text.split()
    lines, current = [], ""
    for word in words:
        if current and len(current) + 1 + len(word) > width:
            lines.append(current)
            current = word
        else:
            current = (current + " " + word).strip()
    if current:
        lines.append(current)
    return lines


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache-dir", default=None)
    parser.add_argument("--out", default=RESULTS)
    parser.add_argument("--stdout", action="store_true")
    args = parser.parse_args(argv)

    lines = []
    report(lines.append, cache_dir=args.cache_dir)
    text = "\n".join(lines).rstrip() + "\n"
    if args.stdout:
        sys.stdout.write(text)
        return 0
    with open(args.out, "w") as handle:
        handle.write(text)
    print("wrote %s (%d lines)" % (args.out, len(lines)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
