#!/usr/bin/env python
"""P3.4: run the baseline-stability check over the whole-brain connectome.

    python scripts/check_whole_brain_stability.py

Needs the gitignored `data/connectome` cache (`scripts/fetch_connectome.py`).
Writes `results/whole_brain_stability.txt`, which is the committed record of
the verification: `tests/test_stability.py` re-derives the same facts from
the real files when the cache is present and from the fifteen-region
fixtures when it is not, so this file is documentation, not an input to
anything.

For each of the three resolutions it reports the network as
`connectome/build.py` ships it (`weight_scale=1.0`, `baseline_input=0.0`),
the same network with baselines balanced but weights unscaled, and the
network put through the P3.4 procedure (`stability.stabilize`).
"""

import argparse
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))

from neurocascade import connectome, stability  # noqa: E402

RESULTS = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "results", "whole_brain_stability.txt"
)

#: Candidate regions to probe the stabilized network's responsiveness with,
#: in preference order; the first two present at a given resolution are
#: used. A network made stable by shrinking every weight would pass every
#: check in this script and be useless, so the last block asks whether
#: anything still propagates, and whether it propagates to the right places.
#: The candidates are striatal and motor-cortical because their downstream
#: targets are the ones this codebase's own scenarios already name.
PROBE_CANDIDATES = ("CP", "MOp", "STRd", "MO", "STR", "Isocortex")


def block(lines, title):
    lines.append("")
    lines.append("-" * 72)
    lines.append(title)
    lines.append("-" * 72)


def describe(lines, label, network, n_initial_conditions=5):
    assessment = stability.assess(
        network, n_initial_conditions=n_initial_conditions
    )
    lines.append("")
    lines.append("%s:" % label)
    for line in assessment.summary().split("\n"):
        lines.append("  " + line)
    return assessment


def responsiveness(network, acronyms, probe):
    """Steady-state response of every node to a unit drive step at `probe`.

    Linear response at the operating point: `dr = (I - A)^-1 diag(S') db`,
    with `A = diag(S') W`. Exact for the linearization, which is the regime
    a certified-stable non-saturating network is in by construction.
    """
    A = stability.operating_matrix(network)
    slopes = stability.sigmoid_slopes(network, np.full(network.n, 0.5))
    gain = np.linalg.solve(np.eye(network.n) - A, np.diag(slopes))
    return gain[:, acronyms.index(probe)]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default=RESULTS)
    parser.add_argument(
        "--operating-gain",
        type=float,
        default=stability.DEFAULT_OPERATING_GAIN,
        help="ILLUSTRATIVE dimensionless loop gain rho (default %(default)s)",
    )
    args = parser.parse_args()

    ontology = connectome.load_ontology()
    strength, voxels = connectome.load_knox_inputs(ontology=ontology)

    lines = [
        "Whole-brain baseline stability (P3.4)",
        "=" * 72,
        "",
        "Connectome: Knox et al. 2019 connection density, signed by source-",
        "region transmitter identity, one hemisphere (see connectome/build.py).",
        "Node parameters are connectome.DEFAULT_NODE, which are ILLUSTRATIVE.",
        "Operating gain rho = %g (ILLUSTRATIVE; see stability.py)." % args.operating_gain,
        "",
        "Generated by scripts/check_whole_brain_stability.py.",
    ]

    for resolution in connectome.RESOLUTIONS:
        built = connectome.build_circuit_network(
            strength, voxel_counts=voxels, resolution=resolution
        )
        network = built.network
        block(lines, "resolution=%r: %d nodes" % (resolution, network.n))
        kappa = stability.contraction_number(network)
        lines.append("")
        lines.append(
            "  published weights, unscaled: kappa = %.6g, "
            "critical weight_scale = %.6g" % (kappa, 1.0 / kappa)
        )
        lines.append(
            "  signed input weight per node: min %.4g  median %.4g  max %.4g"
            % (
                network.connectivity.sum(axis=1).min(),
                np.median(network.connectivity.sum(axis=1)),
                network.connectivity.sum(axis=1).max(),
            )
        )

        describe(lines, "as built (baseline_input=0, weight_scale=1)", network)
        describe(
            lines,
            "baselines balanced, weights still unscaled",
            stability.balanced_baselines(network),
        )
        stabilized = stability.stabilize(network, operating_gain=args.operating_gain)
        lines.append("")
        for line in stabilized.summary().split("\n"):
            lines.append("  " + line)
        assessment = describe(lines, "P3.4 procedure applied", stabilized.network)

        lines.append("")
        lines.append("  responsiveness of the stabilized network:")
        probes = [a for a in PROBE_CANDIDATES if a in built.acronyms][:2]
        for probe in probes:
            response = responsiveness(stabilized.network, built.acronyms, probe)
            order = np.argsort(-np.abs(response))
            moved = int((np.abs(response) > 1e-3).sum())
            lines.append(
                "    unit drive step at %-4s moves %3d/%d nodes by >1e-3; "
                "largest: %s"
                % (
                    probe,
                    moved,
                    network.n,
                    ", ".join(
                        "%s %+.3f" % (built.acronyms[k], response[k])
                        for k in order[:6]
                    ),
                )
            )
        lines.append("")
        lines.append("  VERDICT for resolution=%r: %s" % (resolution, "ok" if assessment.ok else "NOT ok"))

    text = "\n".join(lines) + "\n"
    with open(args.out, "w") as handle:
        handle.write(text)
    print(text)


if __name__ == "__main__":
    main()
