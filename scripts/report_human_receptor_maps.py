#!/usr/bin/env python
"""The human whole-brain receptor maps, written down as a committed record.

    python scripts/report_human_receptor_maps.py

Needs the gitignored `data/human` cache (`scripts/fetch_human_connectome.py`
and `scripts/fetch_human_expression.py`). Writes
`results/human_receptor_maps.txt`.

This is the human analogue of the mouse P4.3 validation step: for every one
of the 40 receptor/transporter genes the stable ENIGMA AHBA release carries,
turn its expression row into a relative density map over the same 82-region
Desikan-Killiany atlas the human connectome uses (`human/relative_density`,
normalization=\"max\"), and record the regions the map says are highest. The
four anatomy checks the expression tests already pin (DRD1/DRD2
striatum-dominant, HTR2A cortex-dominant, GABRA1 cortex > striatum, OPRM1
accumbens/striatal/thalamic) are then re-run here on the FULL 82-region
file, not on the twelve-region fixture, so the fixture is validated against
the real data it was cut from rather than only asserted to be a verbatim
slice.

No number in this file is invented. Every value is `max`-normalized AHBA
expression from the checksum-verified ENIGMA file, under the
proportionality ASSUMPTION `human/expression.py` states; a value is a
relative density, not a receptor density, and the two regions the published
file leaves all-NaN (`R_frontalpole`, `R_temporalpole`) stay NaN rather
than being filled.
"""

import argparse
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))

from neurocascade import human  # noqa: E402
from neurocascade.human import expression as expr  # noqa: E402

RESULTS = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    "..",
    "results",
    "human_receptor_maps.txt",
)

#: The anatomy checks the expression tests pin, restated as `(gene, is_peak,
#: description)` where `is_peak(peak_label)` decides whether the FULL-file
#: peak agrees with the independently known distribution. These are the four
#: checks `tests/test_human_expression.py` asserts on the fixture; running
#: them on the full file is what makes this report a validation rather than
#: a printout.
_STRIATAL = {
    "Lcaud", "Rcaud", "Lput", "Rput", "Laccumb", "Raccumb",
}
ANATOMY_CHECKS = [
    (
        ("DRD1", "DRD2"),
        lambda peak: peak in _STRIATAL,
        "D1/D2 dopamine receptors are striatum-dominant (caudate/putamen/accumbens)",
    ),
    (
        ("HTR2A",),
        lambda peak: peak.startswith(("L_", "R_")),
        "5-HT2A is cortex-dominant (peak is a cortical region)",
    ),
    (
        ("OPRM1",),
        lambda peak: peak in _STRIATAL or peak in {"Lthal", "Rthal"},
        "mu-opioid receptor is accumbens/striatal/thalamic (peak is one of those)",
    ),
]

#: The GABRA1 check is a comparison, not a peak test: its expression in
#: cortex must exceed its expression in striatum.
GABRA1_CHECK = "GABRA1 cortex > caudate"


def block(lines, title):
    lines.append("")
    lines.append("-" * 72)
    lines.append(title)
    lines.append("-" * 72)


def full_name(atlas, label):
    region = atlas.by_label[label]
    return "%s (%s)" % (region.name, region.kind)


def gene_row(expression, symbol, top_n=5):
    rho = human.relative_density(expression, symbol, normalization="max")
    top = rho.top(top_n)
    peak = top[0][0]
    return peak, top


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default=RESULTS)
    args = parser.parse_args()

    conn = human.load_connectome(allow_download=False)
    expression = human.load_expression(allow_download=False)
    atlas = conn.atlas

    if list(expression.region_labels) != list(conn.labels):
        raise RuntimeError(
            "expression and connectome region orders disagree; they must be "
            "one shared meaning of 'region' for a receptor map to exist"
        )

    lines = [
        "Human whole-brain receptor maps (AHBA expression -> Desikan-Killiany)",
        "=" * 72,
        "",
        "Expression: ENIGMA AHBA (abagen-processed), 82 regions x 40 stable",
        "receptor genes (cross-donor r >= 0.2). Connectome: the same ENIGMA",
        "Desikan-Killiany atlas, so region i means the same region on both",
        "sides. Values are `max`-normalized relative density: 1.0 at each",
        "gene's peak region, others expressed as a fraction of it. NOT a",
        "receptor density (mRNA is not protein, protein is not binding",
        "sites); see human/expression.py for the ASSUMPTION.",
        "",
        "Generated by scripts/report_human_receptor_maps.py.",
    ]

    block(lines, "Regions the published file leaves unmeasured (kept as NaN)")
    if expression.regions_without_values():
        for label in expression.regions_without_values():
            lines.append("  %-16s %s" % (label, full_name(atlas, label)))
    else:
        lines.append("  none")

    # --- peak + top-5 summary ---------------------------------------------
    block(lines, "Peak region and top-5, per gene (normalization=max)")
    peak_by_symbol = {}
    for symbol in expression.symbols:
        gene = expr.gene(symbol)
        peak, top = gene_row(expression, symbol)
        peak_by_symbol[symbol] = peak
        lines.append(
            "  %-9s %-13s %-9s peak=%-24s %s"
            % (
                symbol,
                gene.system,
                peak,
                full_name(atlas, peak),
                ", ".join(
                    "%s %.3f" % (label, value) for label, value in top[1:]
                ),
            )
        )

    # --- the anatomy checks ----------------------------------------------
    block(lines, "Anatomy checks, re-run on the full 82-region file")
    all_ok = True
    for symbols, is_peak, description in ANATOMY_CHECKS:
        for symbol in symbols:
            peak = peak_by_symbol[symbol]
            ok = bool(is_peak(peak))
            all_ok = all_ok and ok
            lines.append(
                "  %-8s %-12s peak=%-24s %s"
                % (
                    symbol,
                    "PASS" if ok else "FAIL",
                    full_name(atlas, peak),
                    description,
                )
            )
    gabra1_cortex = human.relative_density(
        expression, "GABRA1", normalization="max"
    )
    cortex_values = [
        gabra1_cortex.for_region(label)
        for label in expression.region_labels
        if atlas.by_label[label].kind == "cortex"
        and np.isfinite(gabra1_cortex.for_region(label))
    ]
    caudate_value = gabra1_cortex.for_region("Lcaud")
    gabra1_ok = bool(max(cortex_values) > caudate_value)
    all_ok = all_ok and gabra1_ok
    lines.append(
        "  %-8s %-12s cortex max=%.3f  Lcaud=%.3f  %s"
        % (
            "GABRA1",
            "PASS" if gabra1_ok else "FAIL",
            max(cortex_values),
            caudate_value,
            GABRA1_CHECK,
        )
    )
    lines.append("")
    lines.append("  OVERALL: %s" % ("all anatomy checks pass" if all_ok else "A CHECK FAILED"))

    # --- full top-10 per gene --------------------------------------------
    block(lines, "Top-10 regions per gene (normalization=max)")
    for symbol in expression.symbols:
        gene = expr.gene(symbol)
        rho = human.relative_density(expression, symbol, normalization="max")
        lines.append("")
        lines.append("  %s  [%s]  %s" % (symbol, gene.system, gene.protein))
        for label, value in rho.top(10):
            lines.append(
                "    %-34s %-28s %.6f"
                % (label, full_name(atlas, label), value)
            )

    text = "\n".join(lines) + "\n"
    with open(args.out, "w") as handle:
        handle.write(text)
    print(text)


if __name__ == "__main__":
    main()
