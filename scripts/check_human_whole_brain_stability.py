#!/usr/bin/env python
"""Human analogue of P3.4: baseline stability over the human connectome.

    python scripts/check_human_whole_brain_stability.py

Needs the gitignored `data/human` cache (`scripts/fetch_human_connectome.py`).
Writes `results/human_whole_brain_stability.txt`, which is the committed
record of the verification. The same check and the same procedure
(`stability.stabilize` / `stability.assess`) apply to the human network
unchanged: `human/build.py` returns the same species-neutral
`CircuitNetwork` type the mouse builder does.

The one difference from the mouse script is structural rather than
numerical. The human matrix is UNDIRECTED and UNSIGNED (diffusion
tractography), so `human/build.py` signs each source region from cited
transmitter identity and excludes the two unsigned amygdala columns. That
is a data-layer convention, stated in `human/build.py` and
`human/neurotransmitter.py`; nothing in `stability.py` knows or cares.
"""

import argparse
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))

from neurocascade import human, stability  # noqa: E402

RESULTS = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    "..",
    "results",
    "human_whole_brain_stability.txt",
)

#: Candidate source regions to probe the stabilized network's responsiveness
#: with. Motor cortex and caudate are the human Desikan-Killiany analogues of
#: the mouse script's motor-cortical and striatal probes: their downstream
#: targets are the ones this codebase's own scenarios already name.
PROBE_CANDIDATES = ("L_precentral", "R_precentral", "Lcaud", "Rcaud")


def block(lines, title):
    lines.append("")
    lines.append("-" * 72)
    lines.append(title)
    lines.append("-" * 72)


def describe(lines, label, network, n_initial_conditions=5):
    assessment = stability.assess(
        network, n_initial_conditions=n_initial_conditions
    )
    lines.append("")
    lines.append("%s:" % label)
    for line in assessment.summary().split("\n"):
        lines.append("  " + line)
    return assessment


def responsiveness(network, labels, probe):
    """Steady-state response of every node to a unit drive step at `probe`.

    Linear response at the operating point: `dr = (I - A)^-1 diag(S') db`,
    with `A = diag(S') W`. Exact for the linearization, which is the regime
    a certified-stable non-saturating network is in by construction.
    """
    A = stability.operating_matrix(network)
    slopes = stability.sigmoid_slopes(network, np.full(network.n, 0.5))
    gain = np.linalg.solve(np.eye(network.n) - A, np.diag(slopes))
    return gain[:, labels.index(probe)]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default=RESULTS)
    parser.add_argument(
        "--operating-gain",
        type=float,
        default=stability.DEFAULT_OPERATING_GAIN,
        help="ILLUSTRATIVE dimensionless loop gain rho (default %(default)s)",
    )
    args = parser.parse_args()

    conn = human.load_connectome(allow_download=False)
    built = human.build_circuit_network(conn)
    network = built.network

    lines = [
        "Human whole-brain baseline stability",
        "=" * 72,
        "",
        "Connectome: ENIGMA Toolbox group-average Desikan-Killiany structural",
        "matrix (68 cortical + 14 subcortical regions), diffusion-MRI",
        "tractography from unrelated healthy young adults of the Human",
        "Connectome Project. UNDIRECTED and UNSIGNED; each source region is",
        "signed from cited transmitter identity (human/neurotransmitter.py)",
        "and the two unsigned amygdala columns are excluded. See",
        "docs/architecture.md, \"The human layer\".",
        "Node parameters are connectome.DEFAULT_NODE, which are ILLUSTRATIVE.",
        "Operating gain rho = %g (ILLUSTRATIVE; see stability.py)." % args.operating_gain,
        "",
        "Generated by scripts/check_human_whole_brain_stability.py.",
    ]

    block(lines, "%d nodes (%d cortical + %d subcortical)" % (
        network.n, len(conn.atlas.cortical()), len(conn.atlas.subcortical()),
    ))
    lines.append("")
    lines.append(built.report.summary())

    kappa = stability.contraction_number(network)
    lines.append("")
    lines.append(
        "  published weights, unscaled: kappa = %.6g, "
        "critical weight_scale = %.6g" % (kappa, 1.0 / kappa)
    )
    lines.append(
        "  signed input weight per node: min %.4g  median %.4g  max %.4g"
        % (
            network.connectivity.sum(axis=1).min(),
            np.median(network.connectivity.sum(axis=1)),
            network.connectivity.sum(axis=1).max(),
        )
    )

    describe(lines, "as built (baseline_input=0, weight_scale=1)", network)
    describe(
        lines,
        "baselines balanced, weights still unscaled",
        stability.balanced_baselines(network),
    )
    stabilized = stability.stabilize(network, operating_gain=args.operating_gain)
    lines.append("")
    for line in stabilized.summary().split("\n"):
        lines.append("  " + line)
    assessment = describe(lines, "P3.4 procedure applied", stabilized.network)

    lines.append("")
    lines.append("  responsiveness of the stabilized network:")
    probes = [label for label in PROBE_CANDIDATES if label in built.labels][:2]
    for probe in probes:
        response = responsiveness(stabilized.network, built.labels, probe)
        order = np.argsort(-np.abs(response))
        moved = int((np.abs(response) > 1e-3).sum())
        lines.append(
            "    unit drive step at %-14s moves %3d/%d nodes by >1e-3; "
            "largest: %s"
            % (
                probe,
                moved,
                network.n,
                ", ".join(
                    "%s %+.3f" % (built.labels[k], response[k])
                    for k in order[:6]
                ),
            )
        )
    lines.append("")
    lines.append("  VERDICT: %s" % ("ok" if assessment.ok else "NOT ok"))

    text = "\n".join(lines) + "\n"
    with open(args.out, "w") as handle:
        handle.write(text)
    print(text)


if __name__ == "__main__":
    main()
