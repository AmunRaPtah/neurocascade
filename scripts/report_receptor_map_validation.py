#!/usr/bin/env python
"""P4.3: write the committed record of the receptor maps against anatomy.

    python scripts/report_receptor_map_validation.py

Needs the gitignored `data/expression` and `data/connectome` caches
(`scripts/fetch_expression.py`, `scripts/fetch_connectome.py`). Writes
`results/receptor_map_validation.txt`.

Like P4.1's coverage report and P4.2's density-validation report, this file
is documentation and not an input to anything: `tests/test_expression_
anatomy.py` re-derives every claim's outcome offline from the committed
fixtures, and `tests/test_multi_region_scenario.py` re-derives the
mu-opioid substitution. The point of committing the text is that the
outcome of the validation is readable in a clean checkout without the
caches and without running anything.

Every number here is computed from the Allen unionizes and the claim
records in `expression/anatomy.py`. Nothing is copied from a docstring.
"""

import argparse
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))

from neurocascade import scenarios  # noqa: E402
from neurocascade.legacy import connectome, expression
from neurocascade.legacy.expression import anatomy, scenario_maps  # noqa: E402

RESULTS = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    "..",
    "results",
    "receptor_map_validation.txt",
)

RULE = "=" * 72
THIN = "-" * 72


def _wrap(text, width=68):
    lines, current = [], ""
    for word in text.split():
        if len(current) + len(word) + 1 > width:
            lines.append(current)
            current = word
        else:
            current = (current + " " + word).strip()
    if current:
        lines.append(current)
    return lines


def report(out, cache_dir=None):
    ontology = connectome.load_ontology()
    atlas = expression.load_expression_atlas(
        ontology=ontology,
        symbols=list(anatomy.VALIDATED_SYMBOLS),
        cache_dir=cache_dir,
    )

    out(RULE)
    out("Receptor maps against independently known distributions (P4.3)")
    out(RULE)
    out("")
    out("Generated by scripts/report_receptor_map_validation.py.")
    out("Expression policy for every number below: plane=%r, combine=%r."
        % (anatomy.DEFAULT_PLANE, anatomy.DEFAULT_COMBINE))
    out("")
    for line in _wrap(
        "These claims are bug detectors, not findings. A concordant claim "
        "that fails means the ingestion or the normalization is wrong. "
        "Claims are ordinal only - min(high) > max(low) - because P4.2 "
        "measured this conversion to be a good ordering (Spearman ~0.71 "
        "against mouse D1 autoradiography) and a bad scale (proportional "
        "R2 0.31, log-log slope 0.46). A claim is ASSERTED by the test "
        "suite only when its source separates the two groups by at least "
        "%.0f of the source's own tiers; single-tier claims are REPORTED "
        "here and their outcome printed either way." % anatomy.ASSERTABLE_SEPARATION
    ):
        out("  " + line)
    out("")

    # --- 1. the sources ----------------------------------------------------
    out(THIN)
    out("1. The cited expected distributions")
    out(THIN)
    out("")
    for key in sorted(anatomy.ANATOMY_SOURCES):
        source = anatomy.ANATOMY_SOURCES[key]
        out("  [%s] %s" % (key, source.citation))
        if source.pmid or source.doi:
            out("      PMID %s, doi %s" % (source.pmid or "-", source.doi or "-"))
        out("      %s | %s | measured: %s"
            % (source.species, source.method.split(";")[0], source.modality))
        for line in _wrap("scale: " + source.scale, 62):
            out("      " + line)
        out("")

    # --- 2. every claim ----------------------------------------------------
    results = anatomy.check_atlas(atlas, ontology=ontology)
    out(THIN)
    out("2. Every claim, measured")
    out(THIN)
    out("")
    out("  %d claims over %d receptors: %s"
        % (len(results), len(anatomy.VALIDATED_SYMBOLS),
           ", ".join(anatomy.VALIDATED_SYMBOLS)))
    out("")
    for result in results:
        claim = result.claim
        out("  %s %s" % ("ASSERTED" if claim.assertable else "reported ",
                         claim.describe()))
        out("      expected to hold: %s | separation: %.1f tier(s)"
            % (claim.expected_to_hold, claim.separation))
        values = ", ".join(
            "%s %.4g" % (region, result.values[region])
            for region in claim.regions if region in result.values
        )
        out("      measured: %s" % values)
        if result.missing:
            out("      NOT MEASURED: %s" % ", ".join(result.missing))
        out("      min(high) %.4g vs max(low) %.4g, ratio %.3g -> holds=%s, %s"
            % (result.min_high, result.max_low, result.ratio, result.holds,
               "as recorded" if result.ok else "UNEXPECTED"))
        for line in _wrap("evidence: " + claim.evidence, 62):
            out("      " + line)
        if claim.mechanism:
            for line in _wrap(
                "mechanism [%s]: %s" % (claim.mechanism_source.key, claim.mechanism),
                62,
            ):
                out("      " + line)
        out("")

    unexpected = anatomy.failures(results)
    out("  %d of %d claims behaved as recorded; %d did not; %d unmeasured."
        % (len(results) - len(unexpected) - len(anatomy.unmeasured(results)),
           len(results), len(unexpected), len(anatomy.unmeasured(results))))
    out("")

    # --- 3. the one disagreement, sized ------------------------------------
    out(THIN)
    out("3. The disagreements, sized")
    out(THIN)
    out("")
    if not unexpected:
        out("  None.")
    for result in unexpected:
        out("  %s" % result.claim.describe())
        out("      ratio %.4g (a claim holds when this is > 1)" % result.ratio)
    out("")
    full = atlas.for_connectome(
        connectome.load_connectome(ontology=ontology),
        plane=anatomy.DEFAULT_PLANE,
        combine=anatomy.DEFAULT_COMBINE,
    )
    row = full.for_gene("Oprm1")
    row = row[np.isfinite(row)]
    out("  Context for the Oprm1 cortex/cerebellum pair, over all %d measured"
        % row.size)
    out("  regions of the 291-region connectome matrix:")
    out("    Oprm1 min %.4f, 10th percentile %.4f, median %.4f, max %.4f"
        % (row.min(), np.percentile(row, 10), np.median(row), row.max()))
    for acronym in ("MOp", "CBX", "LC", "PAG", "VTA", "CP", "MH"):
        value = float(
            atlas.energy_matrix(
                [int(ontology.id_for_acronym(acronym))],
                symbols=["Oprm1"],
                plane=anatomy.DEFAULT_PLANE,
                combine=anatomy.DEFAULT_COMBINE,
            ).for_gene("Oprm1")[0]
        )
        out("    %-4s %.4f  (percentile %.1f of the whole-brain Oprm1 map)"
            % (acronym, value, 100.0 * (row < value).mean()))
    out("")

    # --- 4. policy sensitivity ---------------------------------------------
    out(THIN)
    out("4. Does the plane x combine policy change any conclusion?")
    out(THIN)
    out("")
    for line in _wrap(
        "P4.1 refused to default the two policies and P4.2 priced the "
        "refusal for its D1 correlation. This is the same price for these "
        "claims. A policy row that differs from the others is a modelling "
        "decision hiding inside a default."
    ):
        out("  " + line)
    out("")
    agreement = anatomy.policy_agreement(atlas, ontology=ontology)
    out("    %-24s %-10s %12s %12s" % ("plane", "combine", "unexpected", "unmeasured"))
    for plane, combineare in sorted(agreement):
        counts = agreement[(plane, combineare)]
        out("    %-24s %-10s %12d %12d"
            % (plane, combineare, counts["unexpected"], counts["unmeasured"]))
    out("")

    # --- 5. the cross-gene check -------------------------------------------
    out(THIN)
    out("5. Are the Drd1 and Drd2 rows the anatomy they claim to be?")
    out(THIN)
    out("")
    for line in _wrap(
        "The one cross-gene check, and the only legitimate shape for one: a "
        "ratio of within-gene ratios, so the per-experiment probe and "
        "segmentation differences that make expression energy "
        "incomparable between genes cancel instead of being ignored. Well "
        "above 1 means Drd2 is midbrain-weighted relative to Drd1, which is "
        "the D2-autoreceptor anatomy [bello2011]; near 1 would mean the two "
        "gene rows had been shuffled into each other."
    ):
        out("  " + line)
    out("")
    contrast_ids = [
        int(ontology.id_for_acronym(a)) for a in ("VTA", "SNc", "CP")
    ]
    contrast_expression = atlas.energy_matrix(
        contrast_ids, symbols=["Drd1", "Drd2"],
        plane=anatomy.DEFAULT_PLANE, combine=anatomy.DEFAULT_COMBINE,
    )
    for region, value in sorted(
        anatomy.midbrain_dopamine_contrast(contrast_expression).items()
    ):
        out("    (Drd2[%s]/Drd2[CP]) / (Drd1[%s]/Drd1[CP]) = %.1f"
            % (region, region, value))
    out("")

    # --- 6. the mu-opioid map replacement ----------------------------------
    out(THIN)
    out("6. The multi-region mu-opioid map: hand-written -> atlas-derived")
    out(THIN)
    out("")
    handwritten = scenarios.mu_opioid_multi_region_coupling_handwritten()
    gain = scenarios.mu_opioid_mechanism_gain()
    nodes = scenarios.MU_OPIOID_MULTI_REGION_STRUCTURES
    derived = scenarios.mu_opioid_multi_region_coupling(source="cache")
    density_map = scenario_maps.scenario_density_map(
        "Oprm1", nodes, scenarios.MU_OPIOID_REFERENCE_NODE, source="cache",
    )
    out("    %-18s %8s %8s %10s %10s %8s"
        % ("node", "region", "rho", "mech gain", "coupling", "was"))
    for node in ("VTA_GABA", "PAG_Interneuron", "LC"):
        out("    %-18s %8s %8.3f %10.2f %10.3f %8.2f"
            % (node,
               ontology.acronym_for_id(nodes[node]),
               density_map.for_region(nodes[node]),
               gain,
               derived[node],
               handwritten[node]))
    out("")
    for line in _wrap(
        "One illustrative mechanism gain for all three nodes, because "
        "`Simulation.rhs` adds `gain * activation` to a node's OWN drive "
        "and the downstream amplification the old map folded into LC's "
        "gain is already carried by the connectivity weight. Its scale is "
        "set by a stated rule (leave the geometric mean of the two "
        "interneuron-motif couplings where the hand-tuning put it) and is "
        "not load-bearing: every qualitative result of the scenario and of "
        "its P3.3 connectome port survives for any scale in roughly [1.3, "
        "2.0]. The tightest directional margin over the four "
        "network-by-baseline combinations is 2.7e-3 at this scale against "
        "2.6e-3 for the hand-written map, i.e. the substitution does not "
        "cost margin. Holding VTA_GABA at its old -3.0 and letting PAG "
        "follow the density to -7.57 does: the PAG interneuron saturates "
        "and the naloxone reversal of analgesia_index under rest-balanced "
        "baselines falls to 1.9e-4."
    ):
        out("  " + line)
    out("")
    out("    rho normalization: %s" % density_map.units)
    out("    plane=%r, combine=%r, experiments %s"
        % (density_map.source.plane, density_map.source.combine,
           density_map.source.dataset_ids))
    out("")
    for line in _wrap(
        "Every plane x combine policy that has data for Oprm1, so that what "
        "the policy is worth for THIS map can be read rather than assumed. "
        "It is not worth nothing: LC above VTA survives all fourteen "
        "policies, but PAG above VTA does not - the sagittal experiments "
        "put PAG at 0.82-0.90 of VTA where the coronal one puts it at 2.52. "
        "The scenario uses coronal-else-sagittal, which for Oprm1 means the "
        "single whole-brain coronal experiment 79912572; the sagittal "
        "pipeline sections one hemisphere only, which is why P4.1 made the "
        "policy a required argument rather than a default."
    ):
        out("  " + line)
    out("")
    spread = scenario_maps.policy_spread(
        "Oprm1", nodes, scenarios.MU_OPIOID_REFERENCE_NODE, source="cache"
    )
    out("    %-24s %-10s %8s %8s %8s"
        % ("plane", "combine", "VTA", "PAG", "LC"))
    for plane, combine_rule in sorted(spread):
        values = spread[(plane, combine_rule)]
        out("    %-24s %-10s %8.3f %8.3f %8.3f"
            % (plane, combine_rule, values["VTA_GABA"],
               values["PAG_Interneuron"], values["LC"]))
    out("")
    for line in _wrap(
        "The transcript map orders these three LC > PAG > VTA. The one "
        "mouse whole-brain mu-opioid PROTEIN atlas, [erbs2015], orders them "
        "the other way by one tier: VTA ++, LPAG +/++, LC +. Both are "
        "recorded, in expression/anatomy.py's Oprm1 claims, and neither is "
        "used to adjust the other. What the disagreement bounds is how much "
        "of the analgesia/sedation gain split is data: a factor of about "
        "4.3 across three regions in transcript against one semiquantitative "
        "tier in protein."
    ):
        out("  " + line)
    out("")

    # --- 7. what this does not claim ---------------------------------------
    out(THIN)
    out("7. What this validation does not claim")
    out(THIN)
    out("")
    for line in _wrap(
        "It does not claim the maps are right. Ordinal agreement with six "
        "cited distributions rules out the failure modes that matter for an "
        "ingestion (a transposed matrix, a shifted gene column, a "
        "structure-id mis-join, a normalization along the wrong axis) and "
        "rules out nothing about the mRNA-to-protein step, which P4.2 "
        "measured separately and found to be worth a factor of 172 for the "
        "dopamine transporter. Two of the claims here are expected to fail "
        "for exactly that reason and are asserted to fail."
    ):
        out("  " + line)
    out("")
    for symbol in anatomy.VALIDATED_SYMBOLS:
        record = anatomy.mismatch_context(symbol)
        if record is not None:
            out("    %-8s mismatch.py: %s" % (symbol, record.severity))
    out("")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache-dir", default=None)
    parser.add_argument("--out", default=RESULTS)
    parser.add_argument("--stdout", action="store_true")
    args = parser.parse_args(argv)

    lines = []
    report(lines.append, cache_dir=args.cache_dir)
    text = "\n".join(lines).rstrip() + "\n"
    if args.stdout:
        sys.stdout.write(text)
        return 0
    with open(args.out, "w") as handle:
        handle.write(text)
    print("wrote %s (%d lines)" % (args.out, len(lines)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
