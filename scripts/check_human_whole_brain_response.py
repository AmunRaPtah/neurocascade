#!/usr/bin/env python
"""A drug run through the human whole-brain network, end to end.

    python scripts/check_human_whole_brain_response.py

Needs the gitignored `data/human` cache. Writes
`results/human_whole_brain_response.txt`.

This is the first full `engine.Simulation` on the human layer: the ENIGMA
Desikan-Killiany connectome, stabilized (`stability.stabilize`, rho = 0.9),
with the mu-opioid receptor system from `scenarios.py` composed onto it
through the human AHBA OPRM1 expression map (`human.whole_brain_simulation`).
The drug is fentanyl at 148.6 nM, the 50 ng/mL overdose exposure
`tests/test_scenarios_calibrated.py` already cites (Moss et al. 2020).

The honest headline is written into the file, not just this docstring:

* the connectome, the expression map and the receptor system's own binding/
  PK numbers are sourced (human where their modules say human);
* the node parameters, the operating gain rho, and the mechanism gain are
  ILLUSTRATIVE - no human mechanism gain has ever been fitted here.

So the RESULT is a human-data-driven response PATTERN (which regions move
most, and in which direction), not a calibrated prediction of magnitude.
"""

import argparse
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))

from neurocascade import human, scenarios  # noqa: E402

RESULTS = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    "..",
    "results",
    "human_whole_brain_response.txt",
)

#: The documented overdose exposure the calibrated mu-opioid tests use.
FENTANYL_OVERDOSE_NM = 148.6  # 50 ng/mL, Moss et al. 2020 (see scenarios.py)


def block(lines, title):
    lines.append("")
    lines.append("-" * 72)
    lines.append(title)
    lines.append("-" * 72)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default=RESULTS)
    parser.add_argument(
        "--dose-nm", type=float, default=FENTANYL_OVERDOSE_NM,
        help="fentanyl bolus concentration in nM (default %(default)s)",
    )
    args = parser.parse_args()

    conn = human.load_connectome(allow_download=False)
    expression = human.load_expression(allow_download=False)
    scenario = human.whole_brain_simulation(
        expression,
        "OPRM1",
        pk_models=scenarios.mu_opioid_pk_models_calibrated(),
        receptor_site=scenarios.mu_opioid_receptor_site_calibrated(),
        mechanism_gain=scenarios.MU_OPIOID_MECHANISM_GAIN,
        connectome=conn,
    )
    names = {r.label: r.name for r in conn.atlas.regions}
    labels = conn.labels

    t_eval = np.linspace(0.0, 60.0, 200)
    baseline = scenario.simulation.run(
        dose_concentrations=[0.0, 0.0], t_span=(0.0, 60.0), t_eval=t_eval
    )
    drug = scenario.simulation.run(
        dose_concentrations=[args.dose_nm, 0.0], t_span=(0.0, 60.0), t_eval=t_eval
    )

    lines = [
        "Human whole-brain response: fentanyl at the mu-opioid receptor",
        "=" * 72,
        "",
        "Composed by human/whole_brain_simulation(): ENIGMA Desikan-Killiany",
        "connectome + human AHBA OPRM1 expression + the calibrated mu-opioid",
        "receptor system from scenarios.py, integrated by engine.Simulation.",
        "Fentanyl bolus = %g nM (the 50 ng/mL overdose exposure, Moss et al."
        % args.dose_nm,
        "2020, cited in tests/test_scenarios_calibrated.py).",
        "",
        "Generated by scripts/check_human_whole_brain_response.py.",
    ]

    block(lines, "Provenance of every layer")
    lines.append("")
    lines.append(scenario.report.summary())

    # --- what the receptor layer alone says --------------------------------
    block(lines, "The expression map's peak, before the circuit acts")
    rho = human.relative_density(expression, "OPRM1", normalization="max")
    for label, value in rho.top(5):
        lines.append(
            "  %-24s %-28s %.6f" % (label, names[label], value)
        )

    # --- the run -----------------------------------------------------------
    block(lines, "The run")
    baseline_deviation = float(np.abs(baseline["rates"][:, -1] - 0.5).max())
    peak_occupancy = float(drug["occupancy"][0].max())
    lines.append(
        "  baseline (no drug): every node rests at the stabilized operating "
        "point, max deviation from 0.5 = %.3g" % baseline_deviation
    )
    lines.append(
        "  fentanyl peak occupancy at the mu site: %.3f" % peak_occupancy
    )

    delta = drug["rates"][:, -1] - baseline["rates"][:, -1]
    moved = int((np.abs(delta) > 1e-3).sum())
    all_down = bool(np.all(delta <= 0.0))
    lines.append(
        "  response at t=60 min: %d of %d nodes moved by >1e-3, and every "
        "moved node is SUPPRESSED (mu-opioid agonism is inhibitory): %s"
        % (moved, len(delta), "yes" if all_down else "NO")
    )

    order = np.argsort(-np.abs(delta))
    lines.append("")
    lines.append("  top responders (|delta rate|, at t=60 min):")
    for k in order[:12]:
        lines.append(
            "    %-24s %-28s %+.4f"
            % (labels[k], names[labels[k]], delta[k])
        )

    # --- what is and is not claimed ---------------------------------------
    block(lines, "What this result is, and what it is not")
    lines.append(
        "  The connectome and the expression map are human data, so the "
        "PATTERN - thalamus and accumbens among the largest responders, every "
        "OPRM1-bearing node suppressed - is a data-driven human result."
    )
    lines.append(
        "  The MAGNITUDE is not calibrated: the mechanism gain is the mouse "
        "scenarios' illustrative MU_OPIOID_MECHANISM_GAIN (no human gain has "
        "ever been fitted), the node parameters are the illustrative mouse "
        "defaults, and rho = 0.9 is the illustrative operating gain. A "
        "reader must not read the numbers above as a prediction of how far a "
        "human brain moves."
    )

    text = "\n".join(lines) + "\n"
    with open(args.out, "w") as handle:
        handle.write(text)
    print(text)


if __name__ == "__main__":
    main()
