#!/usr/bin/env python
"""P4.1: write the committed record of what the ISH ingestion actually covers.

    python scripts/report_expression_coverage.py

Needs the gitignored `data/expression` and `data/connectome` caches
(`scripts/fetch_expression.py`, `scripts/fetch_connectome.py`). Writes
`results/expression_coverage.txt`, which is documentation rather than an
input to anything: `tests/test_expression.py` re-derives every fact in it,
from the real files when the caches are present and from the committed
fixtures when they are not.

The point of committing it is that the two things this task must not hide
are then visible in a clean checkout, without the caches and without running
anything: the gene that has no data at all, and the connectome regions the
ISH data cannot reach.

Every number printed is measured here. Nothing is copied from the manifest
except the citation and the units.
"""

import argparse
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))

from neurocascade import connectome, expression  # noqa: E402

RESULTS = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    "..",
    "results",
    "expression_coverage.txt",
)

RULE = "=" * 72
THIN = "-" * 72


def report(out):
    ontology = connectome.load_ontology()
    matrix = connectome.load_connectome(ontology=ontology)
    atlas = expression.load_expression_atlas(ontology=ontology)
    region_ids = [int(i) for i in matrix.source_ids]

    out("Allen ISH receptor-gene expression coverage (P4.1)")
    out(RULE)
    out("")
    out("Source:   %s" % expression.ALLEN_ISH_CITATION)
    out("Quantity: %s" % expression.EXPRESSION_ENERGY_UNITS)
    out("")
    out("Ontology: CCF structure graph 1, shared with the P3.1 connectome.")
    out("Regions:  the %d source regions of %s." % (matrix.n_source, matrix.dataset_key))
    out("Manifest: %s" % expression.MANIFEST_VERSION)
    out("")
    out("Generated by scripts/report_expression_coverage.py.")
    out("")

    out(THIN)
    out("Genes with NO usable data")
    out(THIN)
    out("")
    for entry in atlas.unavailable_report():
        gene = expression.gene(entry["symbol"])
        out("%s  (%s, Entrez %d, %s)" % (
            gene.symbol, gene.protein, gene.entrez_id, gene.phase
        ))
        out("  searched:   %s" % entry["searched"])
        out("  conclusion: %s" % entry["conclusion"])
        out("")
    out(
        "%d of %d genes have ISH data; %d with none."
        % (
            len(atlas.symbols()),
            len(expression.RECEPTOR_GENES),
            len(atlas.missing_symbols()),
        )
    )
    out("")

    out(THIN)
    out("Per-gene coverage over the %d connectome regions" % matrix.n_source)
    out(THIN)
    out("")
    out(
        "%-9s %-34s %5s %-18s %s"
        % ("gene", "protein", "n_exp", "planes", "regions")
    )
    for row in atlas.coverage_report(structure_ids=region_ids):
        out(
            "%-9s %-34s %5d %-18s %d/%d"
            % (
                row["symbol"],
                row["protein"][:34],
                row["n_experiments"],
                ",".join(row["planes"]),
                row["n_regions_covered"],
                row["n_regions_requested"],
            )
        )
    out("")

    orphans = atlas.experiments_without_unionizes()
    out(
        "Indexed experiments with no structure unionizes in any graph: %d"
        % len(orphans)
    )
    for dataset in sorted(orphans, key=lambda d: d.id):
        out("  %d  %s  %s" % (dataset.id, dataset.symbol, dataset.plane))
    out("")

    out(THIN)
    out("Regions the ISH data cannot reach")
    out(THIN)
    out("")
    energy = atlas.for_connectome(
        matrix, plane="coronal-else-sagittal", combine="mean"
    )
    missing = energy.regions_without_values()
    out(
        "plane='coronal-else-sagittal', combine='mean': %d genes x %d regions, "
        "%.2f%% of cells measured."
        % (len(energy.symbols), energy.structure_ids.size, 100.0 * energy.coverage())
    )
    out("")
    out(
        "%d of %d regions carry no expression energy for ANY gene:"
        % (len(missing), matrix.n_source)
    )
    for structure_id in missing:
        structure = ontology[structure_id]
        out("  %-8s %s" % (structure.acronym, structure.name))
    out("")
    out(
        "These are the same twelve in every experiment, which is what makes"
    )
    out(
        "them a property of the reference space the ISH grid is registered to"
    )
    out(
        "(pre-CCFv3 P56) rather than of any gene. See expression/sources.py,"
    )
    out("MISSING_FROM_ISH.")
    out("")

    out(THIN)
    out("How much the choice of plane and combine rule matters")
    out(THIN)
    out("")
    out("Coverage of the %d x %d cell grid under each policy:" % (
        len(atlas.symbols()), matrix.n_source
    ))
    out("")
    for plane in expression.PLANE_POLICIES:
        grid = atlas.energy_matrix(region_ids, plane=plane, combine="mean")
        lost = grid.genes_without_values()
        out(
            "  plane=%-22s %6.2f%% measured, %d gene(s) with no map%s"
            % (
                plane,
                100.0 * grid.coverage(),
                len(lost),
                (": " + ", ".join(lost)) if lost else "",
            )
        )
    out("")

    pooled = atlas.energy_matrix(region_ids, plane="any", combine="mean")
    out(
        "Disagreement between a gene's experiments, over the cells where at"
    )
    out("least two of them report a value (plane='any'):")
    out("")
    out("%-9s %6s %10s %10s" % ("gene", "cells", "median r", "max r"))
    for symbol in atlas.symbols():
        experiments = atlas[symbol].select("any")
        if len(experiments) < 2:
            continue
        stack = np.vstack([e.energy_for(region_ids) for e in experiments])
        counts = np.isfinite(stack).sum(axis=0)
        # Only columns at least two experiments report can be compared; the
        # rest are excluded first so no all-NaN reduction is attempted.
        comparable = counts >= 2
        ratio = np.full(counts.shape, np.nan)
        if np.any(comparable):
            block = stack[:, comparable]
            with np.errstate(invalid="ignore", divide="ignore"):
                low = np.nanmin(block, axis=0)
                high = np.nanmax(block, axis=0)
                ratio[comparable] = np.where(low > 0, high / low, np.nan)
        usable = comparable & np.isfinite(ratio)
        if not np.any(usable):
            continue
        out(
            "%-9s %6d %10.2f %10.2f"
            % (
                symbol,
                int(usable.sum()),
                float(np.median(ratio[usable])),
                float(np.max(ratio[usable])),
            )
        )
    out("")
    out(
        "r is max/min across the experiments that report a region. The median"
    )
    out(
        "column is the one to read: the max column is dominated by regions"
    )
    out(
        "where one experiment saw almost nothing, so it diverges rather than"
    )
    out("measuring anything. A median r of 1.2 (Gria3) and one of 31 (Chrm3)")
    out("are the two ends of what 'the expression of a gene in a region'")
    out("means in this data, and they are why `combine` has no default.")
    out("P4.2 owns the choice; nothing here makes it.")
    out("")
    out(
        "plane='any', combine='mean' for reference: %d cells measured of %d."
        % (int(np.isfinite(pooled.values).sum()), pooled.values.size)
    )


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out", default=RESULTS, help="where to write (default: results/)"
    )
    parser.add_argument(
        "--stdout", action="store_true", help="print instead of writing"
    )
    args = parser.parse_args(argv)

    lines = []
    report(lines.append)
    text = "\n".join(lines) + "\n"
    if args.stdout:
        sys.stdout.write(text)
        return 0
    with open(args.out, "w") as handle:
        handle.write(text)
    print("wrote %s (%d lines)" % (args.out, len(lines)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
