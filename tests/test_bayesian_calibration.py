# Every test here runs real DEMetropolisZ chains, which is why the whole
# module is `slow` and sits out the per-task gate. It is NOT excused from
# passing. `autonomous_runner.py --verify-full` runs it daily and reports
# through the digest.
pytestmark = pytest.mark.slow

# Expected shape of each system's "predicted" Deterministic (number of
# equilibrium-occupancy values its forward model returns), used by the
# smoke tests below; must match each `_simulate_*_raw` function's return
# length in bayesian_calibration.py. GABA-A's vector shrank from three
# entries to two in P11.3: the third was the behavioural anxiolysis ratio,
# retired with its rodent dataset.
_PREDICTED_LENGTH = {"mu_opioid": 1, "d2": 2, "gaba_a": 2}

#: Which entries of each system's `predicted` vector are receptor
#: occupancies (bounded in [0, 1] by construction) and which are something
#: else. No system carries a behavioural-ratio entry any more: the only one
#: ever fitted left with P11.3's retirement, and its reproduction lives in
#: the quarantine-recovery tests below rather than in a likelihood term.
_OCCUPANCY_ENTRIES = {"mu_opioid": (0,), "d2": (0, 1), "gaba_a": (0, 1)}
_RATIO_ENTRIES = {"mu_opioid": (), "d2": (), "gaba_a": ()}


def _run_smoke_test_for_system(system_name):
    # A few hundred total draws across 2 chains: cheap enough for a test
    # suite, not a claim of production-quality convergence (see module
    # docstring). `save=False` keeps this test from writing into
    # results/calibration/ (the real artifacts are produced by
    # `bayesian_calibration.main()`, run separately; see
    # docs/architecture.md for the diagnostics that run produced).
    idata, prior_idata, summary = bc.run_calibration(
        system_name, draws=120, tune=120, chains=2, cores=1, progressbar=False, save=False
    )

    param_names = bc.SYSTEM_PARAM_NAMES[system_name]
    for name in param_names:
        assert name in idata.posterior.data_vars
        values = idata.posterior[name].values
        assert values.shape == (2, 120)
        assert np.all(np.isfinite(values))

    assert "predicted" in idata.posterior.data_vars
    predicted = idata.posterior["predicted"].values
    assert predicted.shape == (2, 120, _PREDICTED_LENGTH[system_name])
    assert np.all(np.isfinite(predicted))
    for index in _OCCUPANCY_ENTRIES[system_name]:
        occupancies = predicted[:, :, index]
        assert np.all(occupancies >= 0.0)
        assert np.all(occupancies <= 1.0)
    for index in _RATIO_ENTRIES[system_name]:
        ratios = predicted[:, :, index]
        assert np.all(ratios > 0.0)
        # 1e-9 is integrator noise around the exactly-attainable value 1,
        # not a tolerance on a fitted quantity.
        assert np.all(ratios <= 1.0 + 1e-9)

    assert prior_idata is not None
    assert len(summary) == len(param_names)
    assert "r_hat" in summary.columns
    assert "ess_bulk" in summary.columns


def test_smoke_mu_opioid_calibration_runs_and_produces_valid_posterior():
    _run_smoke_test_for_system("mu_opioid")


def test_smoke_d2_calibration_runs_and_produces_valid_posterior():
    _run_smoke_test_for_system("d2")


def test_smoke_gaba_a_calibration_runs_and_produces_valid_posterior():
    _run_smoke_test_for_system("gaba_a")


def test_system_param_names_partition_all_free_parameters_with_no_overlap():
    # Every one of the eight priors.py parameters belongs to exactly one of
    # the three independent per-system models (bc.SYSTEM_PARAM_NAMES), and
    # no parameter is double-counted across systems, which is exactly the
    # "no shared parameters between systems" premise the independent-model
    # restructuring in bayesian_calibration.py's module docstring relies on.
    all_system_params = [
        name for names in bc.SYSTEM_PARAM_NAMES.values() for name in names
    ]
    assert sorted(all_system_params) == sorted(FREE_PARAM_NAMES)
    assert len(all_system_params) == len(set(all_system_params))


#: Names that mark a parameter as belonging to the circuit layer rather
#: than the receptor-binding layer. Nothing carrying any of them may sit in
#: a fit register while the register claims no human behavioural data.
_CIRCUIT_LAYER_MARKERS = (
    "coupling",
    "connection_modulation",
    "tau_",
    "_tau",
    "gain",
    "baseline_input",
    "weight",
)


def _looks_like_circuit_layer(name):
    lowered = name.lower()
    return (
        any(marker in lowered for marker in _CIRCUIT_LAYER_MARKERS)
        or "tau" in lowered
    )


def test_no_circuit_layer_parameter_claims_to_be_calibrated():
    """Acceptance criterion 4 of the species pivot, as an assertion.

    Between P2.2 and P11.3 exactly one circuit-layer parameter was
    calibrated (`gaba_a_connection_modulation_gain`, on rat behaviour), and
    P11.3 retired it with its dataset. Everything this scaffold still fits
    must therefore be a receptor-binding constant, the circuit registers
    must be empty, and no production accessor may advertise a calibrated
    circuit quantity. If a future change adds HUMAN behavioural calibration
    for a circuit-layer parameter, it must edit this test deliberately in
    the same commit - rule 3 of docs/roadmap.md expressed as code.
    """
    # The register itself: empty, so there is nothing to launder through it.
    assert CIRCUIT_LAYER_PARAM_EVIDENCE_KEYS == {}
    for name in CIRCUIT_LAYER_PARAM_EVIDENCE_KEYS:      # pragma: no cover
        raise AssertionError(
            "%s re-entered the circuit register; it must name HUMAN "
            "behavioural evidence in the same commit" % name
        )

    # Every free parameter is a receptor-binding constant, by name.
    for name in FREE_PARAM_NAMES:
        assert not _looks_like_circuit_layer(name), name
        assert name.startswith(("Ki_", "kon_", "koff_")), name

    # Nothing likelihood-updated is a circuit quantity either - this is the
    # list the retired gain sat on until P11.3 removed it.
    for name in LIKELIHOOD_UPDATED_PARAM_NAMES:
        assert not _looks_like_circuit_layer(name), name
    assert set(LIKELIHOOD_UPDATED_PARAM_NAMES) | set(PRIOR_ONLY_PARAM_NAMES) == set(
        FREE_PARAM_NAMES
    )

    # No production scenario function advertises a calibrated circuit-layer
    # quantity. Receptor-system accessors (`gaba_a_receptor_system_
    # calibrated`) are fine; anything whose name carries a circuit marker
    # is exactly the claim P11.3 retired.
    offenders = [
        attr for attr in dir(scenarios)
        if attr.endswith("_calibrated") and _looks_like_circuit_layer(attr)
    ]
    assert offenders == [], (
        "scenarios.py advertises calibrated circuit-layer accessors: %s. "
        "Remove the label or add the human calibration in the same commit."
        % offenders
    )
    assert not hasattr(scenarios, "gaba_a_connection_modulation_calibrated")


# ---------------------------------------------------------------------------
# P11.3: the retired fit stays reproducible from quarantine. These are
# deterministic (a root find on the production forward model, milliseconds),
# not MCMC runs. They exist because retiring a number is not the same as
# deleting it: the committed artefacts in results/calibration/ report a
# posterior over `gaba_a_connection_modulation_gain`, and anyone should be
# able to reconstruct where that posterior came from without trusting the
# artefact files.
# ---------------------------------------------------------------------------

def _historical_ratio_forward(gain, brain_nM=None):
    """The drug/vehicle anxiety-index ratio at `gain`, exactly as P2.2's
    retired likelihood computed it: Phase 1 bridge exposure -> equilibrium
    benzodiazepine occupancy -> amygdala readout ratio, with every number
    except the gain coming from quarantined evidence or unchanged
    production machinery."""
    if brain_nM is None:
        brain_nM = lev.gaba_a_epm_unbound_brain_nM()
    activation = fwd.equilibrium_occupancy_from_kd(3.6, brain_nM, efficacy=1.0)
    network = scenarios.amygdala_anxiety_circuit_network()
    baseline = cfwd.steady_state_rates(
        network, scenarios.gaba_a_connection_modulation(),
        activation=0.0, coupling=scenarios.gaba_a_coupling(),
    )
    return float(cfwd.readout_ratio(
        network, scenarios.anxiety_index_readout(),
        connection_modulation={
            connection: gain
            for connection in scenarios.gaba_a_connection_modulation()
        },
        activation=float(activation),
        coupling=scenarios.gaba_a_coupling(),
        baseline_rates=baseline,
    ))


def _gain_reproducing(target_ratio, brain_nM=None):
    """The gain at which the forward model reproduces `target_ratio`
    exactly. With one free gain and one scalar target this is the maximum
    of the (retired) likelihood."""
    from scipy.optimize import brentq

    return float(brentq(
        lambda gain: _historical_ratio_forward(gain, brain_nM) - target_ratio,
        0.0, 5.0, xtol=1e-11,
    ))


def test_the_null_gain_predicts_an_exact_null():
    """The mechanistic anchor under both the retired fit and any future one:
    a gain of zero leaves the synapse unmodulated, so the drug/vehicle
    ratio is exactly 1 whatever the exposure. The 6e-10 residue is ODE
    integrator noise, not a tolerance on physics."""
    assert _historical_ratio_forward(0.0) == pytest.approx(1.0, abs=1e-8)


def test_the_retired_target_is_reproducible_from_quarantine():
    """The observation behind the only circuit-layer posterior this project
    ever reported, restated from the quarantined module: [Graziani2022]'s
    diazepam 2 mg/kg IP Wistar-rat elevated-plus-maze contrast, reduced to
    an open-arm-avoidance ratio, plus the bridge exposure it was compared
    through."""
    evidence = lev.GABA_A_DIAZEPAM_ANXIOLYSIS_EVIDENCE
    assert "Graziani" in evidence["citation"]
    assert evidence["citation"].rstrip().endswith("PMC9728632)")
    assert evidence["species"] == "rat"
    assert evidence["route"] == "IP"
    assert evidence["dose_mg_per_kg"] == 2.0
    assert evidence["anxiety_ratio_target_mean"] == pytest.approx(
        0.7835128109914594
    )
    assert evidence["anxiety_ratio_target_sd"] == pytest.approx(0.05174, abs=1e-4)
    assert evidence["anxiety_ratio_sd_is_source_propagated"] is True
    # The Phase 1 bridge exposure at P2.2's stated 60 min timepoint.
    assert lev.gaba_a_epm_unbound_brain_nM() == pytest.approx(32.35, abs=0.01)


def test_the_retired_posterior_mean_is_recoverable_from_quarantined_data():
    """The load-bearing reproduction. The committed artefact
    (`results/calibration/gaba_a_summary.csv`) reports a posterior mean of
    0.0742 for the gain. Root-finding the MLE of the same likelihood through
    the SAME forward model, fed ONLY quarantined numbers, lands within ~1e-4
    of it - far inside the posterior's own sd (0.0189). If this drifts, the
    historical artefact and the surviving data have diverged and someone
    must say which one moved."""
    evidence = lev.GABA_A_DIAZEPAM_ANXIOLYSIS_EVIDENCE
    gain = _gain_reproducing(evidence["anxiety_ratio_target_mean"])
    assert gain == pytest.approx(0.0742, abs=2e-3)
    # And the forward model reproduces the target there to well under one
    # observation sd.
    predicted = _historical_ratio_forward(gain)
    assert abs(predicted - evidence["anxiety_ratio_target_mean"]) < 1e-6


def test_the_retired_fit_barely_moves_over_the_unstated_exposure_timepoint():
    """[Graziani2022] does not state its diazepam pre-test interval, and
    the entry refuses to invent one; the retired fit passed 60 min
    explicitly. Reproduced on the quarantined path: across the whole
    plausible window the benzodiazepine site stays near saturation, so
    every timepoint implies essentially the same gain - the historical
    result was not an artefact of the unstated number."""
    evidence = lev.GABA_A_DIAZEPAM_ANXIOLYSIS_EVIDENCE
    target = evidence["anxiety_ratio_target_mean"]
    sd = evidence["anxiety_ratio_target_sd"]
    one_sd_in_gain = (
        _gain_reproducing(target - sd) - _gain_reproducing(target + sd)
    )
    gains = [
        _gain_reproducing(
            target, brain_nM=lev.gaba_a_epm_unbound_brain_nM(t)
        )
        for t in lev.EXPOSURE_TIMEPOINT_SENSITIVITY_MIN
    ]
    assert max(gains) - min(gains) < 0.5 * one_sd_in_gain


def test_the_retired_fit_holds_under_a_second_behavioural_index():
    """The one assumption in the retired fit that no citation backed was
    that the model's anxiety index and the behavioural one move
    proportionally. Its consequence is bounded on the quarantined path too:
    refitting against the independently defined composite EPM anxiety index
    moves the gain by less than the target's own uncertainty already does,
    so the reported number was not an artefact of the index choice."""
    evidence = lev.GABA_A_DIAZEPAM_ANXIOLYSIS_EVIDENCE
    primary = evidence["anxiety_ratio_target_mean"]
    sd = evidence["anxiety_ratio_target_sd"]
    composite = evidence["anxiety_ratio_composite_index_mean"]
    spread = abs(_gain_reproducing(composite) - _gain_reproducing(primary))
    one_sd_in_gain = (
        _gain_reproducing(primary - sd) - _gain_reproducing(primary + sd)
    )
    assert spread < one_sd_in_gain


def test_prior_only_parameters_have_no_matching_likelihood_term():
    # Documents/guards the honesty claim made in priors.py and
    # docs/architecture.md: four of the seven free parameters
    # (Ki_naloxone, kon_dopamine, koff_dopamine, Ki_diazepam) have a real
    # reported sd but no likelihood term updating them against data.
    # Checked by construction (they don't appear anywhere in the relevant
    # system's `_simulate_*_raw` parameter lookups), not by re-deriving a
    # posterior/prior equality numerically (which would need a very long
    # chain to state precisely).
    assert set(LIKELIHOOD_UPDATED_PARAM_NAMES) | set(PRIOR_ONLY_PARAM_NAMES) == set(
        FREE_PARAM_NAMES
    )
    assert set(LIKELIHOOD_UPDATED_PARAM_NAMES) & set(PRIOR_ONLY_PARAM_NAMES) == set()
    # Ki_diazepam_nM returned to this set in P11.3, and that is a real
    # change, not a bookkeeping one: between P2.2 and P11.3 the rodent
    # behavioural-ratio term weakly updated diazepam's affinity through how
    # much diazepam had to be bound to produce the measured anxiolysis.
    # That term left with its dataset, so diazepam's affinity is
    # informed-prior-only again, alongside the other three.
    assert set(PRIOR_ONLY_PARAM_NAMES) == {
        "Ki_naloxone_nM",
        "kon_dopamine_nM_min",
        "koff_dopamine_min",
        "Ki_diazepam_nM",
    }

    raw_sources = {
        name: inspect.getsource(fn)
        for name, fn in [
            ("mu_opioid", bc._simulate_mu_opioid_raw),
            ("d2", bc._simulate_d2_raw),
            ("gaba_a", bc._simulate_gaba_a_raw),
        ]
    }
    for name in PRIOR_ONLY_PARAM_NAMES:
        for system_name, source in raw_sources.items():
            assert name not in source, (
                f"{name} (informed-prior-only) unexpectedly referenced in "
                f"{system_name}'s forward model"
            )


def test_synthetic_recovery_of_a_circuit_layer_gain():
    """`build_circuit_gain_model`, the seam P11.3 left open, actually fits.

    A readout ratio is generated from the production amygdala forward model
    at a KNOWN gain (1.3, deliberately not scenarios.py's illustrative 0.5
    and not any value this project has ever fitted), fed to the builder with
    a wide mechanistic prior, and sampled. The posterior must localise near
    the truth and far from the Uniform(0, 5) mean - which is the
    demonstration that when HUMAN behavioural evidence arrives, fitting a
    circuit-layer parameter is a dataset away, not a rebuild away.
    """
    import pymc as pm

    truth_gain = 1.3
    activation = 0.90
    observed_sd = 0.02

    network = scenarios.amygdala_anxiety_circuit_network()
    baseline = cfwd.steady_state_rates(
        network, scenarios.gaba_a_connection_modulation(),
        activation=0.0, coupling=scenarios.gaba_a_coupling(),
    )
    observed_ratio = float(cfwd.readout_ratio(
        network, scenarios.anxiety_index_readout(),
        connection_modulation={
            connection: truth_gain
            for connection in scenarios.gaba_a_connection_modulation()
        },
        activation=activation,
        coupling=scenarios.gaba_a_coupling(),
        baseline_rates=baseline,
    ))
    # The synthetic observation must be off the mechanistic null by many
    # widths, or the fit below would be recovering the noise floor.
    assert abs(observed_ratio - 1.0) > 10.0 * observed_sd

    model = bc.build_circuit_gain_model(
        prior_lower=0.0, prior_upper=5.0, activation=activation,
        observed_ratio=observed_ratio, sd=observed_sd,
    )
    with model:
        idata = pm.sample(
            draws=400, tune=300, chains=2, cores=1, step=pm.DEMetropolisZ(),
            random_seed=20260824, progressbar=False,
        )
    posterior = idata.posterior["gain"].values
    assert np.all(np.isfinite(posterior))
    recovered_mean = float(posterior.mean())
    recovered_sd = float(posterior.std())
    # Same loose recovery contract as the Kd self-test below: right
    # neighbourhood, posterior spread consistent with the miss.
    assert abs(recovered_mean - truth_gain) < 0.25 * truth_gain
    assert abs(recovered_mean - truth_gain) < 4.0 * recovered_sd


def _generate_synthetic_engine_observation(true_kd_nM, concentration_nM, t_span=(0, 240)):
    """Generate a synthetic "observed" equilibrium occupancy from a REAL
    `engine.Simulation` run (PK model + `ReceptorSite`, the actual
    simulation classes this codebase's forward model is supposed to reuse,
    not the lighter equilibrium-only shortcut `forward.py` uses elsewhere
    in this module for MCMC speed). A single ligand, no circuit coupling
    (coupling={}), on a minimal one-node network, run out to a long enough
    time span that its PK has fully delivered the bolus and its receptor
    occupancy has equilibrated, so the final-time occupancy is a valid
    equilibrium observation.
    """
    from neurocascade.circuit import CircuitNode
    from neurocascade.network import CircuitNetwork

    # kon fixed at the same reference value forward.py uses for a
    # Ki/Kd-only ligand; koff = true_kd * kon reproduces the desired Kd.
    kon = 1.0
    koff = true_kd_nM * kon
    ligand = Ligand(name="synthetic_probe", kon=kon, koff=koff, efficacy=1.0)
    receptor_site = ReceptorSite(name="synthetic_site", ligands=[ligand])
    pk_models = [OneCompartmentPK(ke=1e-6)]  # negligible clearance over t_span
    node = CircuitNode(name="Isolated", tau=1.0, baseline_input=0.0, gain=1.0)
    network = CircuitNetwork(nodes=[node], connectivity=[[0.0]])

    sim = Simulation(
        pk_models=pk_models, receptor_site=receptor_site, network=network, coupling={},
    )
    t_eval = np.linspace(t_span[0], t_span[1], 50)
    result = sim.run(
        dose_concentrations=[concentration_nM], t_span=t_span, t_eval=t_eval
    )
    return float(result["occupancy"][0, -1])


def test_synthetic_recovery_of_known_kd_via_engine_simulation():
    # Generate synthetic data from a REAL engine.Simulation run at a KNOWN
    # Kd deliberately different from any of this module's real literature
    # values (2.5 nM; none of the eight priors.py point estimates is 2.5),
    # so recovering it is a genuine check, not a coincidence of matching
    # some other constant already in the code.
    true_kd = 2.5  # nM
    concentration = 20.0  # nM; well above true_kd so the equilibrium
    # occupancy is in a sensitive (non-saturating, non-floor) part of the
    # C/(C+Kd) curve, giving the likelihood real leverage on Kd.
    synthetic_observed_occupancy = _generate_synthetic_engine_observation(
        true_kd, concentration
    )
    # Cross-check the synthetic data itself against the closed-form
    # equilibrium formula this codebase's occupancy ODE is known to satisfy
    # (see e.g. test_calibrated_kon_koff_reproduce_ki_at_equilibrium in
    # tests/test_scenarios_calibrated.py): occ = C / (C + Kd).
    expected_occupancy = concentration / (concentration + true_kd)
    assert abs(synthetic_observed_occupancy - expected_occupancy) < 1e-3

    model = bc.build_single_kd_model(
        prior_lower=0.1,
        prior_upper=25.0,
        concentration=concentration,
        observed_occupancy=synthetic_observed_occupancy,
        sd=0.01,  # tight: this "observation" is a clean synthetic value,
        # not a real literature figure with known systematic model-mismatch
        # (contrast evidence.py's OCCUPANCY_LIKELIHOOD_SD=0.07).
    )
    import pymc as pm

    with model:
        step = pm.DEMetropolisZ()
        idata = pm.sample(
            draws=300, tune=300, chains=2, cores=1, step=step,
            random_seed=20260726, progressbar=False,
        )

    posterior_kd = idata.posterior["kd"].values
    assert np.all(np.isfinite(posterior_kd))
    recovered_mean = float(posterior_kd.mean())
    recovered_sd = float(posterior_kd.std())

    # Recovery tolerance: within 25% of the true value, a loose bound
    # appropriate for a cheap, short DEMetropolisZ chain (this is a
    # sanity check that the machinery finds the right neighborhood, not a
    # precision benchmark).
    assert abs(recovered_mean - true_kd) < 0.25 * true_kd
    # The true value should also fall within a generous multiple of the
    # posterior's own spread, guarding against a recovered mean that's
    # "close" only by chance while the posterior is wildly overconfident
    # or underdispersed.
    assert abs(recovered_mean - true_kd) < 4 * recovered_sd
