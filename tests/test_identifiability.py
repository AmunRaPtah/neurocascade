def test_no_weight_and_no_tau_comes_out_identifiable(report):
    """P2.3's headline result, computed rather than asserted. If a future
    task adds behavioural data that changes this, this test fails and the
    prose in docs/architecture.md has to be updated with it."""
    by_name = {row["parameter"]: row for row in report}
    assert set(by_name) == {p.name for p in ident.AMYGDALA_PARAMETERS}
    for name in ident.P2_3_TARGET_PARAMETER_NAMES:
        assert by_name[name]["verdict"] != "identifiable", (
            "%s came out identifiable; scenarios.py's illustrative label for "
            "it and docs/architecture.md's P2.3 section both need revisiting"
            % name
        )
    for name in [p.name for p in ident.AMYGDALA_PARAMETERS if p.kind == "tau"]:
        assert by_name[name]["verdict"] == "structurally-unidentifiable"
    # Every non-tau circuit parameter enters only through one of {A,B,C,D},
    # so with the others free none of them can be pinned - the structural
    # degeneracy, reproduced rather than declared.
    for name in ident.STRUCTURALLY_DEGENERATE_PARAMETERS:
        assert by_name[name]["verdict"] == "structurally-degenerate", name
    assert by_name["gaba_a_connection_modulation_gain"]["verdict"] == \
        "one-sided-identifiable"


def test_every_verdict_is_one_of_the_declared_ones(report):
    for row in report:
        assert row["verdict"] in ident.VERDICTS


def test_freeing_the_drug_gain_removes_the_apparent_bounds(report):
    """The pedagogical core of the analysis, restated for the synthetic era.

    With the gain held at scenarios.py's illustrative value, several circuit
    parameters produce bounded profiles - the observation gets matched by
    compensating them, which LOOKS like identification. Freeing the gain
    takes those bounds away, because the compensation was doing the gain's
    job. Stated on named parameters so it cannot pass by accident: the
    count form survives too, and freeing the gain removes more bounds than
    it adds even against a datum the model itself generated.
    """
    by_name = {row["parameter"]: row for row in report}
    for name in ("baseline_input_BLA", "weight_CeA__BLA"):
        assert by_name[name]["bounded_with_gain_fixed"], name
        assert not by_name[name]["bounded_with_gain_free"], name

    circuit_rows = [row for row in report if row["kind"] != "drug_gain"]
    bounded_with_gain_fixed = sum(row["bounded_with_gain_fixed"] for row in circuit_rows)
    bounded_with_gain_free = sum(row["bounded_with_gain_free"] for row in circuit_rows)
    assert bounded_with_gain_fixed >= 2
    assert bounded_with_gain_free < bounded_with_gain_fixed


def test_the_reduced_space_says_what_one_scalar_can_pin(reduced):
    """The table that answers "what did the observation actually constrain?".

    Freeing the whole circuit takes back everything the fixed circuit
    appeared to give: B and C are bounded below, D above, the drug gain below
    only, and A - the one combination bounded on both sides - is bounded so
    widely that the bound is not a measurement. Pinned as computed so a
    circuit change that alters the answer shows up here instead of silently
    rewriting docs/architecture.md's P2.3 section.
    """
    by_key = {row["combination"]: row for row in reduced}
    assert set(by_key) == set(ident.REDUCED_PARAMETERS)

    gain_row = by_key["gaba_a_connection_modulation_gain"]
    assert gain_row["verdict"] == "one-sided-identifiable"
    lower, upper = gain_row["profile_interval"]
    assert lower is not None and upper is None

    for key in ("B", "C", "D"):
        assert by_key[key]["verdict"] == "one-sided-identifiable", key

    # A closes on both sides and is still not identified: its interval spans
    # five orders of magnitude, so what it excludes is the saturated corners
    # where the circuit is dead and no drug effect of any size is possible.
    # That is the distinction `IGNORANCE_SPAN_RATIO` exists to draw, and
    # docs/architecture.md's P2.3 section states the same thing in prose.
    assert by_key["A"]["verdict"] == "practically-unidentifiable"
    assert all(side is not None for side in by_key["A"]["profile_interval"])
    assert by_key["A"]["interval_span_ratio"] > ident.IGNORANCE_SPAN_RATIO
    for key in ("B", "C", "D", "gaba_a_connection_modulation_gain"):
        assert by_key[key]["interval_span_ratio"] == math.inf, key


