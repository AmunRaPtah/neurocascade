def test_closed_form_reproduces_the_integrated_forward_model():
    """The structural argument is made in closed form; the codebase runs an
    integrator. If those two disagree the argument is about a different
    model, so this is the test the rest of the module rests on."""
    activation = ident.default_activation()
    combos = ident.structural_combinations()
    for gain in (
        0.0,
        ident.SYNTHETIC_TRUTH_GAIN,
        scenarios.GABA_A_CONNECTION_MODULATION_GAIN,
        5.0,
    ):
        integrated = ident.predicted_anxiety_ratio(None, gain, activation)
        closed = ident.closed_form_ratio(
            combos["A"], combos["B"], combos["C"], combos["D"], gain, activation)
        assert closed == pytest.approx(integrated, abs=1e-7)


def test_closed_form_still_matches_away_from_the_nominal_circuit():
    """Not just at one point: the reduction has to hold over the region the
    profile likelihood actually explores."""
    activation = ident.default_activation()
    for overrides in (
        {"gain_BLA": 0.4, "baseline_input_BLA": 0.7},
        {"weight_CeA__BLA": 12.0, "gain_CeA": 0.9},
        {"weight_BLA__GABA_Interneuron": -0.4, "baseline_input_CeA": -1.9},
    ):
        combos = ident.structural_combinations(overrides)
        integrated = ident.predicted_anxiety_ratio(overrides, 0.3, activation)
        closed = ident.closed_form_ratio(
            combos["A"], combos["B"], combos["C"], combos["D"], 0.3, activation)
        assert closed == pytest.approx(integrated, abs=1e-6)


def test_the_synthetic_observation_is_the_model_at_its_stated_truth():
    """What replaced the [Graziani2022] rat datum: an observation GENERATED
    by this module's own integrated forward model at `SYNTHETIC_TRUTH_GAIN`,
    so the profiling machinery has a truth to recover and the analysis below
    stays executable while the project waits for human behavioural data."""
    observed = ident.predicted_anxiety_ratio(
        None, ident.SYNTHETIC_TRUTH_GAIN, ident.default_activation())
    assert observed == pytest.approx(ident.OBSERVED_RATIO, abs=1e-12)


def test_the_scenario_gain_is_not_fitted_to_the_synthetic_observation():
    """Guard against the quiet cheat: scenarios.py's illustrative placeholder
    gain must NOT sit at the value that reproduces the observation, or the
    "illustrative" label would be decorative and every regime-A profile
    below would be minimal at the nominal circuit for the wrong reason."""
    at_nominal = ident.predicted_anxiety_ratio()
    gap = abs(at_nominal - ident.OBSERVED_RATIO)
    assert gap > 4.0 * ident.OBSERVED_RATIO_SD


