"""Small committed fixtures: real human connectome data, twelve regions.

Why real data and not a synthetic matrix: the same reason as
`connectome/fixtures` - a hand-written matrix would test array plumbing
and nothing else. The fixture below is a 12 x 12 slice of the
checksum-verified ENIGMA Desikan-Killiany matrix, written back out in the
published format (one label row + one plain numeric matrix). See
`PROVENANCE.md`; `scripts/make_human_fixture.py` regenerates it.

The twelve regions span both hemispheres, five cortical Desikan-Killiany
areas, and all seven subcortical nuclei. The subcortical set includes the
four GABAergic output nuclei (`accumb`, `caud`, `pal`, `put`) so the
builder's inhibitory-exception report is exercised on real labels.

Also here since P12.1: the Hansen 2022 PET receptor-atlas fixtures -- five
verbatim tracer maps and a three-column slice of the paper's deposited
aggregation matrix, with their own load functions below.

And since P12.2: the Zilles & Palomero-Gallagher autoradiography fixtures --
five byte-identical copies of the verified .npy files (receptor names, area
names, and the three strata arrays), the machine-readable absolute-density
table in fmol/mg protein. See `PROVENANCE.md`.

And since P12.3: the CIT168 midbrain-atlas label table -- one byte-identical
copy of the ``info.csv`` inside the verified release bundle, pinning which
nuclei the midbrain registry transcribes. See `PROVENANCE.md`.

And since P13.1: F-TRACT verbatim CSV slices (6 parcels x 6 parcels), synaptic
delay parcel maps, and TVB connectivity signatures for negative-control
rejection testing. See `PROVENANCE.md`.
"""

