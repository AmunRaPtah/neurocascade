"""Small committed fixtures: real human connectome data, twelve regions.

Why real data and not a synthetic matrix: the same reason as
`connectome/fixtures` - a hand-written matrix would test array plumbing
and nothing else. The fixture below is a 12 x 12 slice of the
checksum-verified ENIGMA Desikan-Killiany matrix, written back out in the
published format (one label row + one plain numeric matrix). See
`PROVENANCE.md`; `scripts/make_human_fixture.py` regenerates it.

The twelve regions span both hemispheres, five cortical Desikan-Killiany
areas, and all seven subcortical nuclei. The subcortical set includes the
four GABAergic output nuclei (`accumb`, `caud`, `pal`, `put`) so the
builder's inhibitory-exception report is exercised on real labels.

Also here since P12.1: the Hansen 2022 PET receptor-atlas fixtures -- five
verbatim tracer maps and a three-column slice of the paper's deposited
aggregation matrix, with their own load functions below.

And since P12.2: the Zilles & Palomero-Gallagher autoradiography fixtures --
five byte-identical copies of the verified .npy files (receptor names, area
names, and the three strata arrays), the machine-readable absolute-density
table in fmol/mg protein. See `PROVENANCE.md`.
"""

import os

FIXTURE_DIR = os.path.abspath(os.path.dirname(__file__))

FIXTURE_MATRIX_PATH = os.path.join(
    FIXTURE_DIR, "enigma_hcp_sc_matrix_aparc_with_sctx_fixture.csv"
)
FIXTURE_LABELS_PATH = os.path.join(
    FIXTURE_DIR, "enigma_hcp_sc_labels_aparc_with_sctx_fixture.csv"
)
FIXTURE_EXPRESSION_PATH = os.path.join(
    FIXTURE_DIR, "enigma_hcp_ahba_dk_expression_fixture.csv"
)


def load_fixture_connectome():
    """Load the fixture matrix. No cache, no network, no download path."""
    from ..matrix import read_connectome

    return read_connectome(FIXTURE_MATRIX_PATH, FIXTURE_LABELS_PATH)


def load_fixture_atlas():
    """The twelve-region atlas alone, without the matrix."""
    from ..atlas import atlas_from_labels
    from ..matrix import _read_labels

    return atlas_from_labels(_read_labels(FIXTURE_LABELS_PATH))


def load_fixture_expression():
    """The twelve-region x forty-gene AHBA expression slice.

    No cache, no network, no download path. The slice is verbatim real data
    from the checksum-verified ENIGMA AHBA file (see PROVENANCE.md);
    `scripts/make_human_expression_fixture.py` regenerates it.
    """
    from ..expression import read_expression

    return read_expression(FIXTURE_EXPRESSION_PATH)


# --- Hansen 2022 PET receptor atlas (P12.1) ---------------------------------

#: The five parcellated tracer maps and the aggregation-matrix slice, all
#: generated by `scripts/make_human_receptor_fixture.py`. The tracer files
#: are byte-identical copies of the verified source files (each is a single
#: row of 83 numbers), so a fixture's sha256 equals the manifest entry's;
#: the matrix fixture is a 68 x 3 text-verbatim column slice.
FIXTURE_PET_TRACER_PATHS = {
    "MU_carfentanil_hc204_kantonen": os.path.join(
        FIXTURE_DIR, "hansen_pet_scale033_MU_carfentanil_hc204_kantonen_fixture.csv"
    ),
    "MU_carfentanil_hc39_turtonen": os.path.join(
        FIXTURE_DIR, "hansen_pet_scale033_MU_carfentanil_hc39_turtonen_fixture.csv"
    ),
    "D2_flb457_hc37_smith": os.path.join(
        FIXTURE_DIR, "hansen_pet_scale033_D2_flb457_hc37_smith_fixture.csv"
    ),
    "D2_flb457_hc55_sandiego": os.path.join(
        FIXTURE_DIR, "hansen_pet_scale033_D2_flb457_hc55_sandiego_fixture.csv"
    ),
    "GABAa-bz_flumazenil_hc16_norgaard": os.path.join(
        FIXTURE_DIR,
        "hansen_pet_scale033_GABAa-bz_flumazenil_hc16_norgaard_fixture.csv",
    ),
}

FIXTURE_PUBLISHED_MATRIX_PATH = os.path.join(
    FIXTURE_DIR, "hansen_results_receptor_data_scale033_fixture.csv"
)


def load_fixture_tracer(tracer_key):
    """One tracer's raw `ParcellatedPETMap`, offline."""
    from ..receptors import _TRACERS_BY_KEY, read_parcellated

    if tracer_key not in FIXTURE_PET_TRACER_PATHS:
        raise KeyError(
            "no fixture for %r; committed tracer fixtures are %s"
            % (tracer_key, ", ".join(sorted(FIXTURE_PET_TRACER_PATHS)))
        )
    return read_parcellated(FIXTURE_PET_TRACER_PATHS[tracer_key], tracer_key)


def load_fixture_receptor(receptor_key):
    """One receptor system's relative-density map, built from the fixtures.

    Runs exactly the loader path (`load_receptor`) over fixture bytes
    instead of the verified cache, so the offline tests exercise the same
    z-scoring and combination code the cached run does.
    """
    from ..receptors import RECEPTORS, combine_weighted

    receptor = RECEPTORS[receptor_key]
    maps = [
        load_fixture_tracer(tracer.key).relative_to_cortex()
        for tracer in receptor.tracers
    ]
    if len(maps) == 1:
        return maps[0]
    return combine_weighted(maps, receptor.weights)


def load_fixture_receptors(keys=None):
    """`{key: PETRelativeDensityMap}` for every (or the named) receptors."""
    from ..receptors import receptors_ingested

    keys = receptors_ingested() if keys is None else tuple(keys)
    return {key: load_fixture_receptor(key) for key in keys}


def load_fixture_published_column(receptor_key):
    """One receptor's column of the committed aggregation-matrix slice.

    The anchor the offline bit-exactness tests compare against; see
    `receptors.PUBLISHED_COLUMN_SCALES` for what scale each column is on.
    """
    from ..receptors import read_published_column_slice

    return read_published_column_slice(
        FIXTURE_PUBLISHED_MATRIX_PATH, receptor_key
    )


# --- Zilles & Palomero-Gallagher autoradiography (P12.2) ---------------------

#: The five machine-readable files of the absolute-density deposit,
#: generated by `scripts/make_human_autoradiography_fixture.py`. Each is a
#: byte-identical copy of its checksum-verified cache file (each .npy is a
#: single small array to begin with), so a fixture's sha256 equals the
#: manifest entry's. The supplementary xlsx is deliberately not shipped:
#: fixtures must stay readable without openpyxl.
FIXTURE_AUTORADIOGRAPHY_PATHS = {
    "zilles2017_ReceptorNames_npy": os.path.join(
        FIXTURE_DIR, "zilles2017_ReceptorNames_fixture.npy"
    ),
    "zilles2017_RegionNames_npy": os.path.join(
        FIXTURE_DIR, "zilles2017_RegionNames_fixture.npy"
    ),
    "zilles2017_ReceptData_S_npy": os.path.join(
        FIXTURE_DIR, "zilles2017_ReceptData_S_fixture.npy"
    ),
    "zilles2017_ReceptData_G_npy": os.path.join(
        FIXTURE_DIR, "zilles2017_ReceptData_G_fixture.npy"
    ),
    "zilles2017_ReceptData_I_npy": os.path.join(
        FIXTURE_DIR, "zilles2017_ReceptData_I_fixture.npy"
    ),
}

#: Stratum -> the manifest/fixture key carrying its (44, 15) array.
_STRATUM_FIXTURE_KEYS = {
    "supragranular": "zilles2017_ReceptData_S_npy",
    "granular": "zilles2017_ReceptData_G_npy",
    "infragranular": "zilles2017_ReceptData_I_npy",
}


def load_fixture_autoradiography():
    """The whole autoradiographic table, built from the committed fixtures.

    Runs exactly the loader path (`autoradiography.load_table`) over
    fixture bytes instead of the verified cache, so the offline tests
    exercise the same validation the cached run does.
    """
    import numpy as np

    from ..autoradiography import (
        RECEPTORS,
        STRATA,
        AutoradiographicDensityTable,
        receptors_covered,
    )

    def _array(key):
        return np.load(FIXTURE_AUTORADIOGRAPHY_PATHS[key], allow_pickle=True)

    areas = [str(x) for x in _array("zilles2017_RegionNames_npy")]
    published_names = [str(x) for x in _array("zilles2017_ReceptorNames_npy")]
    expected = tuple(r.published_name for r in RECEPTORS.values())
    if tuple(published_names) != expected:
        raise ValueError(
            "fixture receptor names %s do not match the registry %s"
            % (published_names, list(expected))
        )
    strata_arrays = {
        stratum: _array(_STRATUM_FIXTURE_KEYS[stratum])
        for stratum in STRATA
    }
    return AutoradiographicDensityTable(
        strata_arrays=strata_arrays,
        area_labels=areas,
        receptor_keys=receptors_covered(),
        citation="see autoradiography.ZILLES_CITATION",
    )
