# --- Zilles & Palomero-Gallagher autoradiography (P12.2) --------------------

FIXTURE_ZILLES_NAMES_PATH = os.path.join(
    FIXTURE_DIR, "zilles2017_ReceptorNames_fixture.npy"
)
FIXTURE_ZILLES_REGIONS_PATH = os.path.join(
    FIXTURE_DIR, "zilles2017_RegionNames_fixture.npy"
)
FIXTURE_ZILLES_DENSITIES = {
    "G": os.path.join(FIXTURE_DIR, "zilles2017_ReceptData_G_fixture.npy"),
    "I": os.path.join(FIXTURE_DIR, "zilles2017_ReceptData_I_fixture.npy"),
    "S": os.path.join(FIXTURE_DIR, "zilles2017_ReceptData_S_fixture.npy"),
}


def load_fixture_zilles():
    """Load the Zilles arrays: receptor names, region names, and G/I/S strata.

    No cache, no network, no download path.
    """
    import numpy as np

    names = np.load(FIXTURE_ZILLES_NAMES_PATH, allow_pickle=True)
    regions = np.load(FIXTURE_ZILLES_REGIONS_PATH, allow_pickle=True)
    densities = {
        k: np.load(v, allow_pickle=True) for k, v in FIXTURE_ZILLES_DENSITIES.items()
    }
    return names, regions, densities


#: The original naming convention for the autoradiography fixtures,
#: matching the keys the existing tests import.
FIXTURE_AUTORADIOGRAPHY_PATHS = {
    "zilles2017_ReceptorNames_npy": FIXTURE_ZILLES_NAMES_PATH,
    "zilles2017_RegionNames_npy": FIXTURE_ZILLES_REGIONS_PATH,
    "zilles2017_ReceptData_S_npy": FIXTURE_ZILLES_DENSITIES["S"],
    "zilles2017_ReceptData_G_npy": FIXTURE_ZILLES_DENSITIES["G"],
    "zilles2017_ReceptData_I_npy": FIXTURE_ZILLES_DENSITIES["I"],
}

#: Stratum -> the manifest/fixture key carrying its (44, 15) array.
_STRATUM_FIXTURE_KEYS = {
    "supragranular": "zilles2017_ReceptData_S_npy",
    "granular": "zilles2017_ReceptData_G_npy",
    "infragranular": "zilles2017_ReceptData_I_npy",
}


def load_fixture_autoradiography():
    """The whole autoradiographic table, built from the committed fixtures.

    Runs exactly the loader path (`autoradiography.load_table`) over
    fixture bytes instead of the verified cache, so the offline tests
    exercise the same validation the cached run does.
    """
    import numpy as np

    from ..autoradiography import (
        RECEPTORS,
        STRATA,
        AutoradiographicDensityTable,
        receptors_covered,
    )

    def _array(key):
        return np.load(FIXTURE_AUTORADIOGRAPHY_PATHS[key], allow_pickle=True)

    areas = [str(x) for x in _array("zilles2017_RegionNames_npy")]
    published_names = [str(x) for x in _array("zilles2017_ReceptorNames_npy")]
    expected = tuple(r.published_name for r in RECEPTORS.values())
    if tuple(published_names) != expected:
        raise ValueError(
            "fixture receptor names %s do not match the registry %s"
            % (published_names, list(expected))
        )
    strata_arrays = {
        stratum: _array(_STRATUM_FIXTURE_KEYS[stratum])
        for stratum in STRATA
    }
    return AutoradiographicDensityTable(
        strata_arrays=strata_arrays,
        area_labels=areas,
        receptor_keys=receptors_covered(),
        citation="see autoradiography.ZILLES_CITATION",
    )


